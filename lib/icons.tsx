// Function to get amenity icon by amenity name
export function getAmenityIcon(name: string) {
  const lower = name.toLowerCase();
  if (lower.includes("wi-fi") || lower.includes("wifi") || lower.includes("internet")) return WifiIcon;
  if (lower.includes("air") || lower.includes("ac") || lower.includes("climate")) return AcIcon;
  if (lower.includes("tv") || lower.includes("smart")) return TvIcon;
  if (lower.includes("shower") || lower.includes("bath")) return ShowerIcon;
  if (lower.includes("butler") || lower.includes("service") || lower.includes("turndown")) return ButlerIcon;
  if (lower.includes("bar") || lower.includes("mini") || lower.includes("wine")) return WineIcon;
  if (lower.includes("breakfast") || lower.includes("dining") || lower.includes("kitchen")) return BreakfastIcon;
  if (lower.includes("bed") || lower.includes("king") || lower.includes("sofa")) return BedIcon;
  return ShieldCheckIcon;
}

